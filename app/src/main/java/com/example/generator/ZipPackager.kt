package com.example.generator

import android.content.ContentValues
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import androidx.core.content.FileProvider
import com.example.model.ProjectFile
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.security.MessageDigest
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

object ZipPackager {

    data class PackagingResult(
        val zipFile: File,
        val sizeBytes: Long,
        val sha256: String,
        val entryCount: Int
    )

    /**
     * Packages a collection of in-memory ProjectFiles into a standard .zip archive.
     */
    fun createProjectZip(
        context: Context,
        projectName: String,
        files: List<ProjectFile>
    ): PackagingResult {
        val sanitizedName = projectName
            .replace(Regex("[^a-zA-Z0-9_-]"), "_")
            .lowercase()
            .take(30)
            .ifEmpty { "ai_factory_project" }

        val zipsDir = File(context.cacheDir, "zips").apply { mkdirs() }
        val zipFile = File(zipsDir, "${sanitizedName}_sih_project.zip")

        if (zipFile.exists()) {
            zipFile.delete()
        }

        val rootFolderName = "${sanitizedName}/"

        ZipOutputStream(FileOutputStream(zipFile).buffered()).use { zos ->
            // Add root directory entry
            zos.putNextEntry(ZipEntry(rootFolderName))
            zos.closeEntry()

            for (file in files) {
                // Ensure proper path normalization
                val normalizedPath = file.path.trimStart('/')
                val zipEntryPath = "$rootFolderName$normalizedPath"
                val entry = ZipEntry(zipEntryPath)
                zos.putNextEntry(entry)
                val bytes = file.content.toByteArray(Charsets.UTF_8)
                zos.write(bytes, 0, bytes.size)
                zos.closeEntry()
            }
        }

        val sha256 = computeSha256(zipFile)
        return PackagingResult(
            zipFile = zipFile,
            sizeBytes = zipFile.length(),
            sha256 = sha256,
            entryCount = files.size
        )
    }

    /**
     * Creates an Android Share Intent with FileProvider for sending the ZIP to external apps.
     */
    fun getShareIntent(context: Context, zipFile: File, projectName: String): Intent {
        val authority = "${context.packageName}.fileprovider"
        val contentUri: Uri = FileProvider.getUriForFile(context, authority, zipFile)

        return Intent(Intent.ACTION_SEND).apply {
            type = "application/zip"
            putExtra(Intent.EXTRA_STREAM, contentUri)
            putExtra(Intent.EXTRA_SUBJECT, "AI Factory Project ZIP: $projectName")
            putExtra(
                Intent.EXTRA_TEXT,
                "Here is the complete production codebase and architecture package for $projectName, generated by AI Factory."
            )
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
    }

    /**
     * Exports the ZIP file to the user's public Downloads directory.
     */
    fun exportToPublicDownloads(context: Context, zipFile: File, displayName: String): Result<String> {
        return runCatching {
            val fileName = "${displayName.replace(Regex("[^a-zA-Z0-9_-]"), "_")}_hackathon.zip"

            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                val resolver = context.contentResolver
                val contentValues = ContentValues().apply {
                    put(MediaStore.MediaColumns.DISPLAY_NAME, fileName)
                    put(MediaStore.MediaColumns.MIME_TYPE, "application/zip")
                    put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
                }

                val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, contentValues)
                    ?: throw IllegalStateException("Failed to create MediaStore entry in Downloads")

                resolver.openOutputStream(uri)?.use { outStream ->
                    FileInputStream(zipFile).use { inStream ->
                        inStream.copyTo(outStream)
                    }
                }
                "Saved to Downloads/$fileName"
            } else {
                @Suppress("DEPRECATION")
                val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
                val destination = File(downloadsDir, fileName)
                FileInputStream(zipFile).use { input ->
                    FileOutputStream(destination).use { output ->
                        input.copyTo(output)
                    }
                }
                "Saved to ${destination.absolutePath}"
            }
        }
    }

    private fun computeSha256(file: File): String {
        return try {
            val digest = MessageDigest.getInstance("SHA-256")
            FileInputStream(file).use { fis ->
                val buffer = ByteArray(8192)
                var bytesRead: Int
                while (fis.read(buffer).also { bytesRead = it } != -1) {
                    digest.update(buffer, 0, bytesRead)
                }
            }
            digest.digest().joinToString("") { "%02x".format(it) }
        } catch (e: Exception) {
            "SHA256_UNAVAILABLE"
        }
    }
}
